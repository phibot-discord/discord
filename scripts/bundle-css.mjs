#!/usr/bin/env node
/**
 * Inline src/phi/css/*.css into src/phi/css/bundle.ts so the Takumi renderer
 * needs no CSS files on disk. The .css files are the source of truth; the
 * bundle is generated (and git-ignored) like src/phi/art-compiled.ts.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(fileURLToPath(new URL("..", import.meta.url)));
const cssDir = join(root, "plugins/phi/css");
const outFile = join(cssDir, "bundle.ts");

const files = readdirSync(cssDir)
	.filter((name) => name.endsWith(".css"))
	.sort();

const lines = [
	"/* generated by scripts/bundle-css.mjs from src/phi/css/*.css — do not edit */",
	"/** Inlined Takumi card CSS so the renderer does not need src/phi/css on disk. */",
	"export const PHI_CSS: Record<string, string> = {",
];
for (const name of files) {
	const css = readFileSync(join(cssDir, name), "utf8");
	lines.push(`\t${JSON.stringify(name)}: ${JSON.stringify(css)},`);
}
lines.push("};", "");

writeFileSync(outFile, lines.join("\n"));
console.log(
	`bundle-css: ${files.length} stylesheets → ${relative(root, outFile)}`,
);
